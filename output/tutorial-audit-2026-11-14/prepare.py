def measure(text): return sum(advances.get(ord(c),6) for c in text)
def wrap(text, width):
    lines=[]
    for para in text.split('\n'):
        line=''
        for word in para.split():
            trial=(line+' '+word).strip()
            if measure(trial)>width and line: lines.append(line); line=word
            else: line=trial
        lines.append(line)
    return '\n'.join(lines)

